// Builds public/atlas/packs/abrahamic-world-religions/relationship-sources.js from relationship-locators.csv
// (one row per timeline relationship) and the source registers of the four research dossiers.
// Run from the repository root: node docs/reviews/synchronoptic-timelines/tl7/build-locators.mjs
// Nothing here adds a historical claim: each row only points a relationship already in the pack at the ledger row
// and evidence keys the research gives for it. `editorial` rows are overview groupings (identity-and-edges.md:
// generic editorial containers are not factual origin claims and need no invented historical source).
import { readFileSync, writeFileSync } from 'node:fs';

const DOCS = 'docs/universes/packs/abrahamic-world-religions/';
const HERE = 'docs/reviews/synchronoptic-timelines/tl7/';
const OUT = 'public/atlas/packs/abrahamic-world-religions/relationship-sources.js';
const DOSSIERS = ['judaism-research.md', 'christianity-research.md', 'islam-research.md', 'comparative-evidence.md'];

/* Display spacing only: the dossiers' register titles lost some spaces ("7December1965", "VaticanII"); restore
   them between words and numbers. Words, numbers and punctuation are otherwise kept exactly. */
const spaced = t =>
  t
    .replace(/,(?=\S)/g, ', ')
    .replace(/(\d)(?=[A-Za-z])(?!st\b|nd\b|rd\b|th\b)/g, '$1 ')
    .replace(/([A-Za-z])(?=\d)/g, '$1 ')
    .replace(/(?<!\bMc)(?<=[a-z])(?=[A-Z])/g, ' ')
    .replace(/:(?=\d+[a-z])/g, ': ')
    .replace(/\b([A-Z]\.)(?=[A-Z][a-z])/g, '$1 ')
    .replace(/([a-z])\(/g, '$1 (');

/* source registers: "| KEY | [title](url) | use |" or "| KEY | Author, [title](url), venue | use |" */
const sources = {};
for (const f of DOSSIERS) {
  for (const line of readFileSync(DOCS + f, 'utf8').split('\n')) {
    const m = /^\| ((?:JU|CH|IS|X)\d+) \| (.+?) \|(?: (.*?) \|)?/.exec(line);
    if (!m) continue;
    const link = /\[([^\]]+)\]\((https?:[^)\s]+)\)/.exec(m[2]);
    if (!link) continue;
    const before = m[2].slice(0, link.index).replace(/[,\s]+$/, '');
    const src = { t: spaced((before ? before + ', ' : '') + link[1]), u: link[2], f };
    /* TL-R07 follow-up (X08): the register's "use" column records which route was actually inspected and the
       page/section scope. Keep both: every further link in the row becomes an alternative route (the "use"
       column's links first, since those are the inspected copies), and the "use" text is kept as the scope. */
    const linksIn = cell => [...cell.matchAll(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g)].map(x => ({ t: x[1], u: x[2] }));
    const use = m[3] || '';
    const alt = [...linksIn(use), ...linksIn(m[2]).slice(1)].filter(
      (x, i, a) => x.u !== src.u && a.findIndex(y => y.u === x.u) === i,
    );
    if (alt.length) src.alt = alt.map(x => ({ t: spaced(x.t), u: x.u }));
    const scope = use.replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '$1').trim();
    if (scope) src.scope = spaced(scope);
    sources[m[1]] = src;
  }
}

const rows = readFileSync(HERE + 'relationship-locators.csv', 'utf8')
  .trim()
  .split('\n')
  .slice(1);
const edges = {};
const used = new Set();
for (const row of rows) {
  const [edge, kind, dossier, ledger, evidence] = row.split(',');
  if (edges[edge]) throw new Error('duplicate edge ' + edge);
  if (kind === 'editorial') {
    edges[edge] = { editorial: true, why: 'Overview grouping in this atlas, not a historical claim' };
    continue;
  }
  if (kind !== 'sourced') throw new Error('bad kind ' + row);
  const ev = evidence.split(';').filter(Boolean);
  if (!ev.length) throw new Error('sourced row without evidence ' + edge);
  ev.forEach(k => {
    if (!sources[k]) throw new Error('unknown evidence key ' + k + ' on ' + edge);
    used.add(k);
  });
  edges[edge] = { loc: dossier + ' · ' + ledger, ev };
}
const usedSources = {};
[...used].sort().forEach(k => {
  const { f, ...rest } = sources[k];
  usedSources[k] = rest;
});

const body =
  '/* Religious Traditions atlas — data part: relationship source locators for the synchronoptic timeline\n' +
  '   (timeline.js). GENERATED by docs/reviews/synchronoptic-timelines/tl7/build-locators.mjs from\n' +
  '   relationship-locators.csv and the research dossiers’ source registers; edit the CSV, not this file.\n' +
  '   Keys are <p|m|l>:<from>><to> (parent, merge, tree link). `loc` is the research ledger row that states the\n' +
  '   relationship; `ev` are its evidence keys. `editorial` marks an overview grouping, not a historical claim. */\n' +
  "((window.ATLAS_PACK_PARTS = window.ATLAS_PACK_PARTS || {})['abrahamic-world-religions'] =\n" +
  "  window.ATLAS_PACK_PARTS['abrahamic-world-religions'] || {})['relationship-sources'] = {\n" +
  '  research: ' +
  JSON.stringify(DOCS) +
  ',\n  sources: {\n' +
  Object.entries(usedSources)
    .map(([k, v]) => '    ' + k + ': ' + JSON.stringify(v) + ',')
    .join('\n') +
  '\n  },\n  edges: {\n' +
  Object.entries(edges)
    .map(([k, v]) => '    ' + JSON.stringify(k) + ': ' + JSON.stringify(v) + ',')
    .join('\n') +
  '\n  },\n};\n';
writeFileSync(OUT, body);
console.log(
  rows.length + ' rows; ' + Object.values(edges).filter(e => e.ev).length + ' sourced, ',
  Object.values(edges).filter(e => e.editorial).length + ' editorial; ' + used.size + ' source keys',
);
